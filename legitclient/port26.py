"""Generates the 26.1.2 variants of Prism Client sources (src26/java) from the 1.21.11 sources (src/client/java) by
applying the renames between the two versions. Files listed in HAND are written by hand in src26 and left alone.
Run before build26.py:  python port26.py && python build26.py"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'src', 'client', 'java')
DST = os.path.join(HERE, 'src26', 'java')
HAND = {'com/wailsvlr/prism/render/EspPipelines.java', 'com/wailsvlr/prism/mixin/LightTextureMixin.java',
        'com/wailsvlr/prism/mixin/CameraMixin.java', 'com/wailsvlr/prism/mixin/GameRendererMixin.java',
        'com/wailsvlr/prism/mixin/LevelRendererMixin.java', 'com/wailsvlr/prism/mixin/AbstractContainerScreenMixin.java',
        'com/wailsvlr/prism/mixin/CrafterScreenMixin.java'}

RULES = [
    # GUI drawing: GuiGraphics became GuiGraphicsExtractor, screens and HUD elements "extract" instead of "render"
    (r'\bGuiGraphics\b', 'GuiGraphicsExtractor'),
    (r'\.drawString\(', '.text('),
    (r'\.drawCenteredString\(', '.centeredText('),
    (r'\.renderItemDecorations\(', '.itemDecorations('),
    (r'\.renderItem\(', '.item('),
    (r'public void render\(GuiGraphicsExtractor', 'public void extractRenderState(GuiGraphicsExtractor'),
    (r'public void renderBackground\(GuiGraphicsExtractor', 'public void extractBackground(GuiGraphicsExtractor'),
    (r'super\.render\(g,', 'super.extractRenderState(g,'),
    (r'super\.renderBackground\(g,', 'super.extractBackground(g,'),
    # chunk positions are a record with pack/unpack
    (r'ChunkPos\.asLong\(', 'ChunkPos.pack('),
    (r'(\bcp|\bchunkPos|getPos\(\)|\bpos)\.toLong\(\)', r'\1.pack()'),
    (r'\bcp\.x\b(?!\()', 'cp.x()'),
    (r'\bcp\.z\b(?!\()', 'cp.z()'),
    # Fabric API renames
    (r'net\.fabricmc\.fabric\.api\.client\.keybinding\.v1\.KeyBindingHelper', 'net.fabricmc.fabric.api.client.keymapping.v1.KeyMappingHelper'),
    (r'KeyBindingHelper\.registerKeyBinding\(', 'KeyMappingHelper.registerKeyMapping('),
    (r'net\.fabricmc\.fabric\.api\.client\.rendering\.v1\.world\.', 'net.fabricmc.fabric.api.client.rendering.v1.level.'),
    (r'\bWorldRenderEvents\b', 'LevelRenderEvents'),
    (r'\bWorldRenderContext\b', 'LevelRenderContext'),
    # inventory clicks
    (r'\bClickType\b', 'ContainerInput'),
    (r'net\.minecraft\.world\.inventory\.ContainerInput', 'net.minecraft.world.inventory.ContainerInput'),
    (r'\.handleInventoryMouseClick\(', '.handleContainerInput('),
    # chat
    (r'getChat\(\)\.addMessage\(', 'getChat().addClientSystemMessage('),
    # level rendering context (Fabric)
    (r'ctx\.worldState\(\)', 'ctx.levelState()'),
    (r'ctx\.matrices\(\)', 'ctx.poseStack()'),
    (r'ctx\.consumers\(\)', 'ctx.bufferSource()'),
    (r'new ChunkPos\(pos\)', 'ChunkPos.containing(pos)'),
]


def main():
    n = 0
    for root, _, files in os.walk(SRC):
        for f in files:
            if not f.endswith('.java'):
                continue
            full = os.path.join(root, f)
            rel = os.path.relpath(full, SRC).replace(os.sep, '/')
            if rel in HAND:
                continue
            text = open(full, encoding='utf-8').read()
            out = text
            for pat, rep in RULES:
                out = re.sub(pat, rep, out)
            for pat, rep in EXTRA.get(rel, []):
                out = out.replace(pat, rep)
            target = os.path.join(DST, rel)
            if out != text:
                os.makedirs(os.path.dirname(target), exist_ok=True)
                with open(target, 'w', encoding='utf-8', newline='\n') as w:
                    w.write('// Generated by port26.py from src/client/java/' + rel + ' for Minecraft 26.1.2. Do not edit; edit the source or port26.py.\n' + out)
                n += 1
            elif os.path.exists(target):
                os.remove(target)
    print(n, 'files ported')


# file-specific fixes that a general rule would get wrong (exact text replacements, applied after RULES)
EXTRA = {
    'com/wailsvlr/prism/PrismClient.java': [('armorView::render', 'armorView::extractRenderState'),
                                            ('VanillaHudElements.STATUS_EFFECTS', 'VanillaHudElements.MOB_EFFECTS'),
                                            ('vanillaEffects.render(vanillaG, vanillaDelta)', 'vanillaEffects.extractRenderState(vanillaG, vanillaDelta)')],
    'com/wailsvlr/prism/modules/PrinterGuide.java': [('Screens.getButtons(', 'Screens.getWidgets(')],
}

if __name__ == '__main__':
    main()
